using AwesomeAssertions;
using sql_storage_engine.Catalog;
using sql_storage_engine.Models.Identifiers;
using sql_storage_engine.Rows;
using sql_storage_engine.Models.Catalog;
using sql_storage_engine.Exposures.Catalog;

using sql_storage_engine.Models.Rows;
namespace sql_storage_engine.UnitTests;
public sealed class IdentityReplicationCodecTests
{
    [TestCase(null)]
    [TestCase(false)]
    [TestCase(true)]
    public void OriginalReplicationFlag_RoundTripsWithoutInventingUnknownValues(bool? flag)
    {
        var table = sql_storage_engine.Exposures.Catalog.CatalogTableExposure.CreateCatalogTable(new sql_storage_engine.Models.Identifiers.TableId { Value = 1 }, "t", 1, new sql_storage_engine.Models.Identifiers.PageId { Value = 2 }, [sql_storage_engine.Exposures.Catalog.CatalogColumnExposure.CreateCatalogColumn(new sql_storage_engine.Models.Identifiers.ColumnId { Value = 1 }, "id", sql_storage_engine.Exposures.Rows.SqlTypeExposure.ReadSqlTypeInt(), false, catalogIdentity: sql_storage_engine.Exposures.Catalog.CatalogIdentityExposure.CreateCatalogIdentity(3,7,flag))]);
        var identity = sql_storage_engine.Exposures.Catalog.CatalogCodecExposure.Decode(sql_storage_engine.Exposures.Catalog.CatalogCodecExposure.Encode(sql_storage_engine.Exposures.Catalog.CatalogDefinitionExposure.CreateCatalogDefinition([table], []))).Tables.Single().Columns.Single().Identity!;
        identity.Seed.Should().Be(3);
        identity.Increment.Should().Be(7);
        identity.IsNotForReplication.Should().Be(flag);
    }

    [Test]
    public void RetainedVersion12Image_MigratesIdentityFlagAsUnknown()
    {
        // Captured from the pre-change format-12 assembly, not regenerated by the current codec.
        var bytes = Convert.FromHexString(File.ReadAllText(Path.Combine(TestContext.CurrentContext.TestDirectory, "TestFixtures", "catalog-identity-v12.hex")).Trim());
        var legacy = sql_storage_engine.Exposures.Catalog.CatalogCodecExposure.Decode(bytes);
        var identity = legacy.Tables.Single().Columns.Single().Identity!;
        identity.Seed.Should().Be(3);
        identity.Increment.Should().Be(7);
        identity.IsNotForReplication.Should().BeNull();
        sql_storage_engine.Exposures.Catalog.CatalogCodecExposure.Decode(sql_storage_engine.Exposures.Catalog.CatalogCodecExposure.Encode(legacy)).Tables.Single().Columns.Single().Identity!.IsNotForReplication.Should().BeNull();
    }

    [Test]
    public void NewlyDeclaredIdentity_DefaultsToOrdinaryReplicationBehavior() => sql_storage_engine.Exposures.Catalog.CatalogIdentityExposure.CreateCatalogIdentity().IsNotForReplication.Should().BeFalse();
}