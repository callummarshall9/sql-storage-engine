using AwesomeAssertions;
using sql_storage_engine.Catalog;
using sql_storage_engine.Identifiers;
using sql_storage_engine.Rows;

namespace sql_storage_engine.UnitTests;

public sealed class IdentityReplicationCodecTests
{
    [TestCase(null)]
    [TestCase(false)]
    [TestCase(true)]
    public void OriginalReplicationFlag_RoundTripsWithoutInventingUnknownValues(bool? flag)
    {
        var table = new CatalogTable(new TableId(1), "t", 1, new PageId(2),
            [new CatalogColumn(new ColumnId(1), "id", SqlType.Int, false, identity: new CatalogIdentity(3, 7, flag))]);
        var identity = CatalogCodec.Decode(CatalogCodec.Encode(new CatalogDefinition([table], [])))
            .Tables.Single().Columns.Single().Identity!;
        identity.Seed.Should().Be(3); identity.Increment.Should().Be(7);
        identity.IsNotForReplication.Should().Be(flag);
    }

    [Test]
    public void RetainedVersion12Image_MigratesIdentityFlagAsUnknown()
    {
        // Captured from the pre-change format-12 assembly, not regenerated by the current codec.
        var bytes = Convert.FromHexString(File.ReadAllText(Path.Combine(TestContext.CurrentContext.TestDirectory,
            "TestFixtures", "catalog-identity-v12.hex")).Trim());
        var legacy = CatalogCodec.Decode(bytes);
        var identity = legacy.Tables.Single().Columns.Single().Identity!;
        identity.Seed.Should().Be(3); identity.Increment.Should().Be(7);
        identity.IsNotForReplication.Should().BeNull();
        CatalogCodec.Decode(CatalogCodec.Encode(legacy)).Tables.Single().Columns.Single()
            .Identity!.IsNotForReplication.Should().BeNull();
    }

    [Test]
    public void NewlyDeclaredIdentity_DefaultsToOrdinaryReplicationBehavior()
        => new CatalogIdentity().IsNotForReplication.Should().BeFalse();
}
